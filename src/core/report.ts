/**
 * 同步报告：<root>/reports/last-sync.md。给 agent 的反馈回路——
 * agent 写完 source.json、触发同步后轮询这份文件的 frontmatter.status，done 之后读正文改错。
 * 每次同步整份重写。
 */

export interface LibReport {
  id: string;
  name: string;
  kind: string;
  /** settings 或 source.json 路径 */
  from: string;
  ok: boolean;
  error?: string;
  total: number;
  free: number;
  withCode: number;
  created: string[];
  updated: number;
}

export interface SyncReport {
  status: "running" | "done";
  trigger: string;
  started: string;
  finished?: string;
  sourcesDir: string;
  sourcesFound: number;
  sourceErrors: string[];
  libraries: LibReport[];
  untagged: string[];
  unknownTags: string[];
  covers?: { made: number; failed: { key: string; error: string }[]; madeFor?: Record<string, string> };
  /** 运行中：当前阶段与进度 */
  progress?: { stage: string; done: number; total: number; current: string };
  /** 整次运行出错（或被取消） */
  error?: string;
  previews?: { checked: number; failed: { key: string; error: string }[] };
}

export function reportMarkdown(r: SyncReport): string {
  const issues =
    (r.error ? 1 : 0) +
    r.sourceErrors.length +
    r.libraries.filter((l) => !l.ok).length +
    (r.previews?.failed.length ?? 0) +
    (r.covers?.failed.length ?? 0);
  const lines = [
    "---",
    "type: ui-shelf-report",
    `status: ${r.status}`,
    `trigger: ${r.trigger}`,
    `started: ${r.started}`,
    `sources_found: ${r.sourcesFound}`,
    `finished: ${r.finished ?? ""}`,
    ...(r.progress ? [`progress: "${r.progress.stage} ${r.progress.done}/${r.progress.total}${r.progress.current ? ` ${r.progress.current}` : ""}"`] : []),
    ...(r.error ? [`error: ${JSON.stringify(r.error)}`] : []),
    `issues: ${issues}`,
    "---",
    "# UI Shelf sync report",
    "",
    "<!-- generated by gogoga UI Shelf — rewritten on every run. Agents: poll until `status` is `done` AND `started` is later than the moment you ran the command; then fix what is listed below. -->",
    "",
  ];
  if (r.status === "running") {
    lines.push("Running…", "");
    if (r.progress) lines.push(`Progress: ${r.progress.stage} ${r.progress.done}/${r.progress.total}${r.progress.current ? ` — now on \`${r.progress.current}\`` : ""}`, "");
    if (r.previews?.failed.length) lines.push("Failures so far:", ...r.previews.failed.map((f) => `- ❌ \`${f.key}\` — ${f.error}`), "");
    return lines.join("\n");
  }
  if (r.error) lines.push(`> ❌ **This run stopped early:** ${r.error}`, "");

  lines.push("## Source files", "", `${r.sourcesFound} file(s) in \`${r.sourcesDir}/\``, "");
  if (r.sourceErrors.length) for (const e of r.sourceErrors) lines.push(`- ❌ ${e}`);
  else if (r.sourcesFound) lines.push("- ✅ all source files are valid");
  lines.push("");

  if (!r.libraries.length)
    lines.push("## Libraries", "", r.trigger.startsWith("check") ? "_This run only checked previews; no library was synced._" : "_No library was synced._", "");
  else lines.push("## Libraries", "", "| Library | From | Result | Components | Free | With code | New |", "| --- | --- | --- | --- | --- | --- | --- |");
  for (const l of r.libraries) {
    const result = l.ok ? "✅" : `❌ ${l.error ?? ""}`.replace(/\|/g, "\\|");
    lines.push(`| ${l.name} (\`${l.id}\`, ${l.kind}) | ${l.from} | ${result} | ${l.total} | ${l.free} | ${l.withCode} | ${l.created.length} |`);
  }
  lines.push("");
  const fresh = r.libraries.flatMap((l) => l.created.map((s) => `${l.id}/${s}`));
  if (fresh.length) lines.push("### New components", "", ...fresh.map((k) => `- \`${k}\``), "");
  const noCode = r.libraries.filter((l) => l.ok && l.free > l.withCode);
  if (noCode.length)
    lines.push(
      "### Free components without code",
      "",
      ...noCode.map((l) => `- ${l.name}: ${l.free - l.withCode} of ${l.free} free components have no code, so their preview falls back to the official page. Add a \`code\` mapping to the source file if the site exposes code.`),
      "",
    );

  if (r.previews) {
    lines.push("## Preview check", "", `Rendered ${r.previews.checked} components.`, "");
    for (const f of r.previews.failed) lines.push(`- ❌ \`${f.key}\` — ${f.error}`);
    lines.push("");
  }
  if (r.covers) {
    lines.push(
      "## Covers",
      "",
      `Generated ${r.covers.made} cover(s): components that had none, plus generated covers whose preview changed since. Components whose source provides an image URL keep that URL; failures below keep their previous cover (or none).`,
      "",
    );
    for (const f of r.covers.failed) lines.push(`- ❌ \`${f.key}\` — ${f.error}`);
    lines.push("");
  }

  lines.push("## Tags", "");
  lines.push(r.untagged.length ? `- ${r.untagged.length} components have no \`ui/type/…\` tag: ${r.untagged.map((k) => `\`${k}\``).join(", ")}` : "- ✅ every component has a type tag");
  if (r.unknownTags.length) lines.push(`- Tags not in the vocabulary: ${r.unknownTags.map((t) => `\`${t}\``).join(", ")}`);
  lines.push("");
  return lines.join("\n");
}
